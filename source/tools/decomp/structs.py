"""Which fields of the structures behind the program's global pointers the code touches.

A global that holds a pointer is read (`rN = g.lw(D_xxxxxxxx);`) and the pointer is then used as a base with constant offsets.
This scans the generated Rust and writes, for every such global, the offsets and access kinds with how often each is seen:
the starting point for naming fields. Output: Docs/Bible/Structs.md (path given as the argument).

    python structs.py ../../decomp/src ../../../Xenogears/Docs/Bible/Structs.md
"""
import re, sys, glob, os, collections

load = re.compile(r'^\s*(r\d+) = g\.lw\((D_[0-9A-F]{8}|[A-Z_]+)\);')
use = re.compile(r'g\.(lbu|lb|lhu|lh|lw|sb|sh|sw|lwl|lwr|swl|swr)\((r\d+)(?:\.wrapping_(add|sub)\((0x[0-9A-F]+|\d+)\))?')
setreg = re.compile(r'^\s*(r\d+) = ')


def main(src, out):
    fields = collections.defaultdict(collections.Counter)
    users = collections.defaultdict(set)
    for path in sorted(glob.glob(os.path.join(src, '*.rs'))):
        if path.endswith('globals.rs'):
            continue
        base = {}
        for line in open(path, encoding='utf-8'):
            if line.startswith('pub unsafe fn'):
                base = {}
                fn = line.split('(')[0].split()[-1]
            m = load.match(line)
            if m:
                base = {k: v for k, v in base.items() if k != m.group(1)}
                base[m.group(1)] = m.group(2)
                continue
            for u in use.finditer(line):
                k, reg, sign, off = u.groups()
                if reg in base:
                    o = int(off, 0) if off else 0
                    if sign == 'sub':
                        o = -o
                    fields[base[reg]][(o, k)] += 1
                    users[base[reg]].add(fn)
            m = setreg.match(line)
            if m and m.group(1) in base and not load.match(line):
                del base[m.group(1)]
    lines = ['# Structures behind global pointers', '',
             'Generated by tools/decomp/structs.py from decomp/src: for every global that holds a pointer, the offsets the code '
             'reads and writes through it (kind, count). Names for these fields go in tools/decomp/names.json once pinned down.', '']
    order = sorted(fields, key=lambda g: -sum(fields[g].values()))
    for g in order[:150]:
        offs = collections.defaultdict(list)
        for (o, k), n in sorted(fields[g].items()):
            offs[o].append('%s x%d' % (k, n))
        lines.append('## %s (%d accesses, %d functions)' % (g, sum(fields[g].values()), len(users[g])))
        lines.append('')
        lines.append(', '.join('+0x%X: %s' % (o if o >= 0 else o, '/'.join(v)) for o, v in sorted(offs.items())))
        lines.append('')
    open(out, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
    print('%d pointer globals, wrote %s' % (len(fields), out))


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
