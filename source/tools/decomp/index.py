"""Function index of the decompiled program: one line per function with its size, what it calls, who calls it and what
kind of thing it touches (geometry engine, the machine's services, the entity table, the state block...), written to
Docs/Bible/Functions.md. Usage: python index.py <decomp/src dir> <out.md>"""
import re, sys, os, json, collections

src, out = sys.argv[1], sys.argv[2]
names = {}
npath = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'names.json')
if os.path.exists(npath):
    names = {int(k, 16): v for k, v in json.load(open(npath)).get('functions', {}).items()}

FN = re.compile(r'^pub unsafe fn f_([0-9A-F]{8})\(')
CALL = re.compile(r'\bf_([0-9A-F]{8})\(g,')
DYN = re.compile(r'g\.call_addr\(0x([0-9A-F]{8})')
mods = sorted(f for f in os.listdir(src) if f.endswith('.rs') and f not in ('lib.rs', 'globals.rs', 'layout.rs', 'modules.rs'))
funcs = collections.OrderedDict()   # addr -> dict
for m in mods:
    cur = None
    for line in open(os.path.join(src, m), encoding='utf-8'):
        mm = FN.match(line)
        if mm:
            cur = int(mm.group(1), 16)
            funcs.setdefault(cur, {'mods': set(), 'lines': 0, 'calls': set(), 'dyn': set(), 'tags': collections.Counter()})
            funcs[cur]['mods'].add(m[:-3])
            continue
        if cur is None:
            continue
        f = funcs[cur]
        f['lines'] += 1
        for c in CALL.findall(line): f['calls'].add(int(c, 16))
        for c in DYN.findall(line): f['dyn'].add(int(c, 16))
        if 'g.gte_' in line: f['tags']['geometry engine'] += 1
        if 'ENTITY_ARRAY' in line or 'entity::' in line: f['tags']['entity table'] += 1
        if 'SCRIPT_CTX' in line or 'script_ctx::' in line: f['tags']['script context'] += 1
        if 'SCRIPT_CODE' in line: f['tags']['script bytecode'] += 1
        if '0x9200' in line: f['tags']['data block'] += 1
        if 'g.lw(0x1F80' in line or 'g.sw(0x1F80' in line or '0x1F801' in line: f['tags']['devices'] += 1
        if 'g.brk(' in line: f['tags']['break'] += 1

callers = collections.defaultdict(set)
for a, f in funcs.items():
    for c in f['calls'] | f['dyn']:
        callers[c].add(a)

def nm(a):
    return names.get(a, 'f_%08X' % a)

L = ['# Function index', '',
     'Generated by tools/decomp/index.py from decomp/src: %d functions in %d modules. Names come from tools/decomp/names.json '
     '("functions"); the rest are addresses. Size is the number of generated lines. Callers count the direct calls '
     'and the computed calls whose target address is a constant.' % (len(funcs), len(mods)), '']
leafs = [a for a, f in funcs.items() if not f['calls'] and not f['dyn']]
roots = [a for a in funcs if not callers.get(a)]
L += ['- leaf functions (call nothing): %d' % len(leafs), '- functions nothing calls directly (entered through pointers, tables or the machine): %d' % len(roots), '']
L += ['## Most called', '', '| function | callers | lines | touches |', '|---|---|---|---|']
for a, c in sorted(callers.items(), key=lambda x: -len(x[1]))[:40]:
    if a not in funcs: continue
    f = funcs[a]
    L.append('| %s (%08X) | %d | %d | %s |' % (nm(a), a, len(c), f['lines'], ', '.join(k for k, _ in f['tags'].most_common(3)) or '-'))
L += ['', '## Largest', '', '| function | lines | calls | callers | touches |', '|---|---|---|---|---|']
for a, f in sorted(funcs.items(), key=lambda x: -x[1]['lines'])[:40]:
    L.append('| %s (%08X) | %d | %d | %d | %s |' % (nm(a), a, f['lines'], len(f['calls'] | f['dyn']), len(callers.get(a, ())), ', '.join(k for k, _ in f['tags'].most_common(3)) or '-'))
by = collections.defaultdict(list)
for a, f in funcs.items():
    for t in f['tags']: by[t].append(a)
L += ['', '## By what they touch', '']
for t, v in sorted(by.items(), key=lambda x: -len(x[1])):
    L.append('- %s: %d functions' % (t, len(v)))
L += ['', '## Per module', '', '| module | functions | lines |', '|---|---|---|']
pm = collections.defaultdict(lambda: [0, 0])
for a, f in funcs.items():
    for m in f['mods']:
        pm[m][0] += 1; pm[m][1] += f['lines']
for m, (n, l) in sorted(pm.items()):
    L.append('| %s | %d | %d |' % (m, n, l))
open(out, 'w', encoding='utf-8').write('\n'.join(L) + '\n')
print('wrote', out, len(funcs), 'functions')
