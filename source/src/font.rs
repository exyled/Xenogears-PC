/// Whether pixel (x 0..5, y 0..8) of the character is ink.
pub fn pixel(c: char, x: usize, y: usize) -> bool {
    let code = c as u32;
    if x >= 5 || y >= 8 || !(0x20..0x7F).contains(&code) { return false; }
    FONT[(code - 0x20) as usize][x] >> y & 1 != 0
}

/// Pixels a string takes at a scale, and the height of a line of it.
pub fn width(text: &str, scale: usize) -> usize { text.chars().count() * 6 * scale }

/// Draws `text` into an image of bw x bh (0x00RRGGBB) with its top left at (x, y); `shadow` draws it once more a pixel
/// (scaled) down and to the right in that colour first.
pub fn draw(buf: &mut [u32], bw: usize, bh: usize, x: usize, y: usize, scale: usize, text: &str, colour: u32, shadow: Option<u32>) {
    let put = |buf: &mut [u32], px: usize, py: usize, col: u32| {
        for dy in 0..scale {
            for dx in 0..scale {
                let (xx, yy) = (px + dx, py + dy);
                if xx < bw && yy < bh { buf[yy * bw + xx] = col; }
            }
        }
    };
    for pass in 0..2 {
        let (col, off) = match (pass, shadow) { (0, Some(s)) => (s, scale), (0, None) => continue, _ => (colour, 0) };
        for (n, c) in text.chars().enumerate() {
            for gx in 0..5 {
                for gy in 0..8 {
                    if pixel(c, gx, gy) { put(buf, x + n * 6 * scale + gx * scale + off, y + gy * scale + off, col); }
                }
            }
        }
    }
}
